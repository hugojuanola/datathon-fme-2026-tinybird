#!/usr/bin/env python3
"""Rewrite the "Current reading" section of README.md from the last row of history.csv.

    python realtime_analyisi_leaderboard/tick.py --since "<UTC>"    # appends the row
    python realtime_analyisi_leaderboard/reading.py                 # refreshes the README from it

Stdlib only. The section is generated: findings and their interpretation live in notes/.
"""
from __future__ import annotations

import csv
import subprocess
from datetime import datetime, timedelta
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODEL_PATHS = ["reco", "offline", "docs/findings.md"]   # where the architecture and the model live


def git(*args: str) -> str:
    try:
        return subprocess.run(["git", *args], cwd=HERE.parent, capture_output=True, text=True, timeout=20).stdout.strip()
    except Exception:
        return ""


def num(row: dict, key: str) -> float | None:
    try:
        return float(row[key])
    except (KeyError, TypeError, ValueError):
        return None


def main() -> None:
    rows = list(csv.DictReader((HERE / "history.csv").open(encoding="utf-8")))
    last = rows[-1]
    cet = (datetime.strptime(last["utc"], "%Y-%m-%d %H:%M") + timedelta(hours=1)).strftime("%d %b %Y, %H:%M")
    conv, ref = num(last, "conv"), num(last, "ref_conv")
    lines = ["## Current reading", "", f"_Generated by the watch from the tick of {cet} CET. Findings are in the notes below._", ""]
    if conv is None or ref is None:   # leaderboard hidden (final round): only our own feedback is available
        lines.append(f"- **The leaderboard is hidden** (mode `{last.get('mode', '')}`); only our own feedback can be read.")
    else:
        lines.append(f"- **Margin to the reference, last hour**: {conv:.3f} against {ref:.3f} — **{conv - ref:+.3f}** "
                     f"({num(last, 'pct_of_way_to_ref'):.0f}% of the way from baseline to reference).")
        c15, r15 = num(last, "conv_15m"), num(last, "ref_conv_15m")
        if c15 is not None and r15 is not None:
            lines.append(f"- **Margin to the reference, last 15 minutes**: {c15:.3f} against {r15:.3f} — **{c15 - r15:+.3f}**.")
        trend = [(r["utc"][11:], num(r, "conv"), num(r, "ref_conv")) for r in rows[-8:] if num(r, "conv") is not None]
        lines.append("- **Trend of the hourly board** (UTC, us / reference): "
                     + " → ".join(f"{t} {a:.2f} / {b:.2f}" for t, a, b in trend) + ".")
        lines.append(f"- **Cold conversion**: {num(last, 'cold'):.2f} against {num(last, 'ref_cold'):.2f}. "
                     f"**Best rival**: {last['best_rival']} at {num(last, 'rival_conv'):.2f}. "
                     f"**On time** (board, last hour): {num(last, 'on_time'):.1f}%. "
                     f"**Model on the board**: `{last['model']}`.")
    served, p95 = num(last, "served_by_team_pct"), num(last, "p95_ms")
    lines.append(f"- **Our own feedback, {last['window']}**: {served:.1f}% of requests answered by us, p95 {p95:.0f} ms; "
                 f"new shoppers {num(last, 'new_conv_pct'):.2f}% ({last['new_requests']} requests), "
                 f"known shoppers {num(last, 'known_conv_pct'):.2f}% ({last['known_requests']}).")
    # which code produced these numbers: the last commit that touched the model, and anything not committed yet
    head = git("log", "-1", "--format=%h — %s (%cd)", "--date=format:%H:%M", "--", *MODEL_PATHS)
    dirty = [ln.split(maxsplit=1)[1] for ln in git("status", "--porcelain", "--", *MODEL_PATHS).splitlines() if len(ln.split()) > 1]
    unpushed = git("log", "origin/javier..HEAD", "--oneline", "--", *MODEL_PATHS).splitlines()
    lines.append(f"- **Architecture and model in the repository**: last commit on `reco/`, `offline/` or the findings: `{head}`. "
                 + ("Everything there is committed" if not dirty else "Not committed yet: " + ", ".join(f"`{d}`" for d in dirty))
                 + ("; all of it is pushed." if not unpushed else f"; {len(unpushed)} model commit(s) waiting for this tick's push."))
    lines.append("- Per-arm numbers of this tick: [`latest.md`](latest.md). Every earlier tick: [`history.csv`](history.csv).")
    lines += ["", ""]
    readme = HERE / "README.md"
    text = readme.read_text(encoding="utf-8")
    a, b = text.index("## Current reading"), text.index("## Notes")
    readme.write_text(text[:a] + "\n".join(lines) + text[b:], encoding="utf-8")
    print("\n".join(lines[:-2]))


if __name__ == "__main__":
    main()
